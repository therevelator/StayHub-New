-- Keep updated_at current on every UPDATE (MySQL did this with ON UPDATE CURRENT_TIMESTAMP)
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "bookings_set_updated_at" BEFORE UPDATE ON "bookings" FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER "maintenance_tasks_set_updated_at" BEFORE UPDATE ON "maintenance_tasks" FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER "properties_set_updated_at" BEFORE UPDATE ON "properties" FOR EACH ROW EXECUTE FUNCTION set_updated_at();

